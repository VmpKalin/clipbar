import AppKit
import Foundation

@MainActor
protocol PasteboardReader: AnyObject {
    /// Returns the pasteboard content when its change count differs from the last seen one.
    func readIfChanged() -> ClipPayload?
    /// Records the current change count so the next `readIfChanged` returns nil (used after
    /// the app itself writes to the pasteboard).
    func markCurrentAsSeen()
    /// The current plain-text content, without affecting change tracking.
    func currentString() -> String
}

@MainActor
final class SystemPasteboardReader: PasteboardReader {
    private static let lastSeenKey = "pasteboard.lastSeenChangeCount"
    private var lastSeen: Int = UserDefaults.standard.object(forKey: lastSeenKey) as? Int ?? -1
    private let pasteboard: NSPasteboard

    /// Types that password managers and other apps use to mark content that must not be stored.
    static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("Pasteboard generator type"),
    ]

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    func readIfChanged() -> ClipPayload? {
        guard pasteboard.changeCount != lastSeen else { return nil }
        remember(pasteboard.changeCount)
        return read()
    }

    func read() -> ClipPayload? {
        let types = pasteboard.types ?? []
        if types.contains(where: { Self.skippedTypes.contains($0) }) { return nil }

        // Files first: copying a file in Finder also puts its icon on the pasteboard as TIFF.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipPayload(text: urls.map { $0.path(percentEncoded: false) }.joined(separator: "\n"))
        }
        if let data = pasteboard.data(forType: .png) { return ClipPayload(imageData: data) }
        if let tiff = pasteboard.data(forType: .tiff),
           let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            return ClipPayload(imageData: png)
        }
        if let s = pasteboard.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipPayload(text: s)
        }
        if let url = pasteboard.string(forType: .URL) ?? pasteboard.string(forType: .init("public.url")) {
            return ClipPayload(text: url)
        }
        return nil
    }

    func markCurrentAsSeen() { remember(pasteboard.changeCount) }

    func currentString() -> String { pasteboard.string(forType: .string) ?? "" }

    private func remember(_ count: Int) {
        lastSeen = count
        UserDefaults.standard.set(count, forKey: Self.lastSeenKey)
    }
}
